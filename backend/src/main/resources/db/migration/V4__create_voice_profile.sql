CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE voice_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT not null REFERENCES app_user (id) ON DELETE CASCADE,
    wav_path text not null,
    embedding vector(256),
    embedding_model varchar(128) not null,
    threshold numeric(4,3),
    active boolean not null default true,
    net_speech_sec numeric(6,2),
    microphone varchar(255),
    recorded_at timestamptz not null,
    created_at timestamptz not null default now(),

    CONSTRAINT threshold_range CHECK (threshold BETWEEN 0 AND 1),
    CONSTRAINT net_speech_non_negative CHECK (net_speech_sec >= 0)
);

-- Felhasználónként legfeljebb egy aktív profil, inaktívból (régi, .bak) bármennyi.
CREATE UNIQUE INDEX voice_profile_one_active_idx
    ON voice_profile (user_id)
    WHERE active = true;

CREATE INDEX voice_profile_user_idx ON voice_profile (user_id);
