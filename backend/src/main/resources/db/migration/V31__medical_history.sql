-- Medical history: anamnézis + kórtörténeti összefoglaló, idővonal, diagnózisok (BNO), gyógyszerek,
-- javaslatok — docs/medical-history.md.
-- TUDATOS DÖNTÉS (a felhasználóé, 2026-10-23): külön táblák, NEM statement — mint a clinical_summary.

-- Dokumentumonkénti kivonat: egyszer készül egy (nem labor-) dokumentumhoz, a kórtörténet ebből épül,
-- így a modell kontextusa nem a teljes leletszövegekkel telik meg. Promptváltáskor (prompt_hash) a
-- Python újraszámolja, a Spring felülírja (dokumentumonként egy sor).
CREATE TABLE document_digest (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT not null,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    -- a vizsgálat / ellátás megnevezése (pl. "Nephrologiai konzílium")
    title varchar(200) not null,
    -- hol járt: intézmény / osztály — csak ha szó szerint szerepel a leletben
    place varchar(300),
    summary text not null,
    -- a kivonatot alátámasztó, szó szerinti idézet a leletből; NULL = nem található, ellenőrizendő
    quote text,
    -- korábbi események az anamnézisből: [{date, title, quote}] — mindegyik idézete a leletben van
    events jsonb not null,
    -- diagnózisok: [{name, bnoCode, since, quote}] — a BNO-kód csak a leletből (szó szerint)
    diagnoses jsonb not null,
    warnings jsonb not null,
    model_name varchar(128) not null,
    seed bigint not null,
    prompt_hash varchar(64) not null,
    extractor_version varchar(64) not null,
    created_at timestamptz not null default now(),

    CONSTRAINT document_digest_one_per_document UNIQUE (document_id),
    -- identitás-kapu: a kivonat betege csak a dokumentum betege lehet
    CONSTRAINT document_digest_document_fk FOREIGN KEY (document_id, patient_id)
        REFERENCES document (id, patient_id) ON DELETE CASCADE,
    CONSTRAINT document_digest_summary_not_blank CHECK (btrim(summary) <> ''),
    CONSTRAINT document_digest_events_array CHECK (jsonb_typeof(events) = 'array'),
    CONSTRAINT document_digest_diagnoses_array CHECK (jsonb_typeof(diagnoses) = 'array'),
    CONSTRAINT document_digest_warnings_array CHECK (jsonb_typeof(warnings) = 'array')
);

CREATE TABLE medical_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    requested_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    requested_at timestamptz not null default now(),
    status varchar(16) not null,
    completed_at timestamptz,
    error text,
    -- az AI anamnézise / kórtörténeti összefoglalója (bekezdések üres sorral)
    summary text,
    -- [{date, title, text, place, documentId, kind, flag}] — minden elem a forrás-dokumentumára mutat
    timeline jsonb,
    -- [{name, bnoCode, date, documentId}]
    diagnoses jsonb,
    -- a kéréskor aktív gyógyszerek pillanatképe (determinisztikus, a gyógyszerlistából): [{id, name, dose, route, verified}]
    medications jsonb not null,
    recommendations jsonb,
    warnings jsonb,
    -- a modellnek átadott adatok azonosítói: {documentIds, labResultIds, medicationIds, allergyIds, recordingSummaryIds}
    input jsonb not null,
    model_name varchar(128),
    seed bigint,
    prompt_hash varchar(64),
    extractor_version varchar(64),
    -- az orvos szerkesztése (korlátozott, a Spring által szűrt HTML); az AI eredetije nem változik
    edited_html text,
    edited_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    edited_at timestamptz,

    CONSTRAINT medical_history_status_values CHECK (status IN ('PROCESSING', 'DONE', 'FAILED')),
    CONSTRAINT medical_history_done_has_text CHECK (status <> 'DONE' OR (summary IS NOT NULL AND btrim(summary) <> '')),
    CONSTRAINT medical_history_failed_has_error CHECK (status <> 'FAILED' OR error IS NOT NULL),
    CONSTRAINT medical_history_timeline_array CHECK (timeline IS NULL OR jsonb_typeof(timeline) = 'array'),
    CONSTRAINT medical_history_diagnoses_array CHECK (diagnoses IS NULL OR jsonb_typeof(diagnoses) = 'array'),
    CONSTRAINT medical_history_medications_array CHECK (jsonb_typeof(medications) = 'array'),
    CONSTRAINT medical_history_recommendations_array CHECK (recommendations IS NULL OR jsonb_typeof(recommendations) = 'array'),
    CONSTRAINT medical_history_warnings_array CHECK (warnings IS NULL OR jsonb_typeof(warnings) = 'array'),
    CONSTRAINT medical_history_edit_complete CHECK (
        (edited_html IS NULL AND edited_by IS NULL AND edited_at IS NULL)
        OR (edited_html IS NOT NULL AND btrim(edited_html) <> '' AND edited_by IS NOT NULL AND edited_at IS NOT NULL)
    ),
    CONSTRAINT medical_history_edit_only_done CHECK (edited_html IS NULL OR status = 'DONE')
);

CREATE INDEX medical_history_patient_idx ON medical_history (patient_id, requested_at DESC);
-- betegenként egyszerre legfeljebb egy készülő kórtörténet (dupla kattintás ellen)
CREATE UNIQUE INDEX medical_history_one_processing_idx ON medical_history (patient_id) WHERE status = 'PROCESSING';
