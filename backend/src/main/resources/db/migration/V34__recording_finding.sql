-- A felvétel átiratából kinyert, csoportosított elemek (docs/voice-module.md, „Csoportok”):
-- panaszok, diagnózisok, beutalók, vizsgálati megállapítások, javasolt gyógyszerek, javaslatok / kontroll.
-- TUDATOS DÖNTÉS: külön táblák, NEM statement (ugyanaz a kivétel, mint a recording_keyword /
-- recording_summary-nél): az orvos szerkeszthető munkalistája. Amit megőrzünk: HOGY (modell, seed,
-- prompt-hash a futáson; az orvos az elemen), MERRE (turn_ids), MIKOR (created_at, edited_at), és az AI
-- eredeti szövege (a szerkesztés mellé kerül, nem felülírja).

-- Egy kinyerési futás (a felvétel elkészültekor automatikusan, utána gombbal újra). A legfrissebb kész
-- futás AI-elemei érvényesek; a korábbiak (és az orvos rajtuk végzett szerkesztései) megmaradnak.
CREATE TABLE recording_extraction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recording_id BIGINT not null REFERENCES recording (id) ON DELETE CASCADE,
    requested_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    requested_at timestamptz not null default now(),
    status varchar(16) not null,
    completed_at timestamptz,
    error text,
    warnings jsonb,
    model_name varchar(128),
    seed bigint,
    prompt_hash varchar(64),

    CONSTRAINT recording_extraction_status_values CHECK (status IN ('PROCESSING', 'DONE', 'FAILED')),
    CONSTRAINT recording_extraction_failed_has_error CHECK (status <> 'FAILED' OR error IS NOT NULL),
    CONSTRAINT recording_extraction_done_has_model CHECK (status <> 'DONE'
        OR (model_name IS NOT NULL AND seed IS NOT NULL AND prompt_hash IS NOT NULL)),
    CONSTRAINT recording_extraction_warnings_array CHECK (warnings IS NULL OR jsonb_typeof(warnings) = 'array')
);

CREATE INDEX recording_extraction_recording_idx ON recording_extraction (recording_id, requested_at DESC);
-- felvételenként egyszerre legfeljebb egy futó kinyerés (dupla kattintás ellen)
CREATE UNIQUE INDEX recording_extraction_one_processing_idx ON recording_extraction (recording_id)
    WHERE status = 'PROCESSING';

-- Egy elem. MODEL: egy futás eredménye (extraction_id); DOCTOR: az orvos adta hozzá (created_by).
-- A text / bno_code az eredeti, nem változik; az orvos szerkesztése az edited_* oszlopokba kerül, a
-- törlés logikai (deleted_*) — az AI javaslata visszakereshető marad.
CREATE TABLE recording_finding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recording_id BIGINT not null REFERENCES recording (id) ON DELETE CASCADE,
    extraction_id BIGINT REFERENCES recording_extraction (id) ON DELETE CASCADE,
    category varchar(16) not null,
    origin varchar(8) not null,
    text varchar(500) not null,
    -- BNO-kód: a modell sosem ad; csak ha az átiratban szó szerint elhangzott, vagy az orvos írja be
    bno_code varchar(10),
    -- MERRE: a hivatkozott megszólalások (utterance.turn_id); az orvos elemén üres is lehet
    turn_ids jsonb not null default '[]',
    -- determinisztikus ellenőrzés jelzése (pl. az átiratban nem szereplő szám) — ellenőrizendő
    flag varchar(500),
    created_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    created_at timestamptz not null default now(),
    edited_text varchar(500),
    edited_bno_code varchar(10),
    edited_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    edited_at timestamptz,
    deleted_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    deleted_at timestamptz,

    CONSTRAINT recording_finding_category_values CHECK (category IN
        ('COMPLAINT', 'DIAGNOSIS', 'REFERRAL', 'EXAM_FINDING', 'MEDICATION', 'RECOMMENDATION')),
    CONSTRAINT recording_finding_origin_values CHECK (origin IN ('MODEL', 'DOCTOR')),
    CONSTRAINT recording_finding_origin_complete CHECK (
        (origin = 'MODEL' AND extraction_id IS NOT NULL AND created_by IS NULL)
        OR (origin = 'DOCTOR' AND extraction_id IS NULL AND created_by IS NOT NULL)),
    CONSTRAINT recording_finding_model_has_source CHECK (origin <> 'MODEL' OR jsonb_array_length(turn_ids) > 0),
    CONSTRAINT recording_finding_turn_ids_array CHECK (jsonb_typeof(turn_ids) = 'array'),
    CONSTRAINT recording_finding_text_not_blank CHECK (btrim(text) <> ''),
    -- BNO-kód csak panasznál és diagnózisnál; formátum: betű + 2 számjegy, opcionálisan pont és 1–4 jel
    CONSTRAINT recording_finding_bno_category CHECK ((bno_code IS NULL AND edited_bno_code IS NULL)
        OR category IN ('COMPLAINT', 'DIAGNOSIS')),
    CONSTRAINT recording_finding_bno_format CHECK (bno_code IS NULL OR bno_code ~ '^[A-Z][0-9]{2}(\.?[0-9A-Z]{1,4})?$'),
    CONSTRAINT recording_finding_edited_bno_format CHECK (edited_bno_code IS NULL
        OR edited_bno_code ~ '^[A-Z][0-9]{2}(\.?[0-9A-Z]{1,4})?$'),
    -- szerkesztés: szöveg + ki + mikor együtt (a BNO-kód a szerkesztésben törölhető, ezért az nullázható)
    CONSTRAINT recording_finding_edit_complete CHECK (
        (edited_text IS NULL AND edited_bno_code IS NULL AND edited_by IS NULL AND edited_at IS NULL)
        OR (edited_text IS NOT NULL AND btrim(edited_text) <> '' AND edited_by IS NOT NULL AND edited_at IS NOT NULL)),
    CONSTRAINT recording_finding_delete_complete CHECK ((deleted_by IS NULL) = (deleted_at IS NULL))
);

CREATE INDEX recording_finding_recording_idx ON recording_finding (recording_id, category, id);
CREATE INDEX recording_finding_extraction_idx ON recording_finding (extraction_id);
