-- A felvétel kulcsszavai és összefoglalója (docs/voice-module.md).
-- TUDATOS DÖNTÉS: külön táblák, NEM statement (ugyanaz a kivétel, mint a clinical_summary-nél):
-- a kulcsszó kiemelés és szűrés, az összefoglaló pedig a teljes átirat szintézise, nem
-- egyenként jóváhagyandó állítás. Amit megőrzünk: ki / melyik modell (HOGY), mikor (MIKOR), és az
-- összefoglaló pontjainál a hivatkozott megszólalások (MERRE: turn_id).

-- Kulcsszó: az AI javasolja (MODEL, javaslat az orvos döntéséig), vagy az orvos adja hozzá (DOCTOR)
CREATE TABLE recording_keyword (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recording_id BIGINT not null REFERENCES recording (id) ON DELETE CASCADE,
    term varchar(200) not null,
    origin varchar(8) not null,
    status varchar(12) not null,
    -- MODEL: a javasló modell; DOCTOR: null
    model_name varchar(128),
    -- DOCTOR: ki adta hozzá; MODEL: ki döntött róla (null, amíg javaslat). RESTRICT: a fiók nem
    -- törölhető, amíg hivatkozik rá
    user_id BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    created_at timestamptz not null default now(),
    decided_at timestamptz,

    CONSTRAINT keyword_origin_values CHECK (origin IN ('MODEL', 'DOCTOR')),
    CONSTRAINT keyword_status_values CHECK (status IN ('SUGGESTED', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT keyword_term_not_blank CHECK (btrim(term) <> ''),
    CONSTRAINT keyword_model_has_model_name CHECK (origin <> 'MODEL' OR model_name IS NOT NULL),
    CONSTRAINT keyword_doctor_is_accepted CHECK (origin <> 'DOCTOR' OR (status = 'ACCEPTED' AND user_id IS NOT NULL)),
    -- AI-javaslatnál: döntés (elfogadás / elutasítás) = időpont + döntő orvos
    CONSTRAINT keyword_decision_complete CHECK (origin = 'DOCTOR'
        OR ((status = 'SUGGESTED') = (decided_at IS NULL) AND (status = 'SUGGESTED') = (user_id IS NULL)))
);

-- Egy felvételnél egy kifejezés egyszer (kis/nagybetű és szélső szóköz nem számít)
CREATE UNIQUE INDEX recording_keyword_unique_term_idx ON recording_keyword (recording_id, lower(btrim(term)));

-- Összefoglaló a teljes átiratból és a (nem elutasított) kulcsszavakból; újragenerálható, az
-- előzmény megmarad (a legfrissebb az érvényes)
CREATE TABLE recording_summary (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recording_id BIGINT not null REFERENCES recording (id) ON DELETE CASCADE,
    requested_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    requested_at timestamptz not null default now(),
    status varchar(16) not null,
    completed_at timestamptz,
    error text,
    summary text,
    -- [{text, turnIds[]}] — mondatonként a hivatkozott megszólalások (a Python ellenőrzi, hogy léteznek)
    points jsonb,
    -- a kéréskor átadott kulcsszavak (pillanatkép: utólag változhatnak)
    keywords jsonb not null,
    -- pl. olyan szám az összefoglalóban, ami az átiratban nem szerepel — kiírjuk, nem csendes
    warnings jsonb,
    model_name varchar(128),
    seed bigint,
    prompt_hash varchar(64),

    CONSTRAINT recording_summary_status_values CHECK (status IN ('PROCESSING', 'DONE', 'FAILED')),
    CONSTRAINT recording_summary_done_has_text CHECK (status <> 'DONE' OR (summary IS NOT NULL AND btrim(summary) <> '')),
    CONSTRAINT recording_summary_failed_has_error CHECK (status <> 'FAILED' OR error IS NOT NULL),
    CONSTRAINT recording_summary_keywords_array CHECK (jsonb_typeof(keywords) = 'array'),
    CONSTRAINT recording_summary_points_array CHECK (points IS NULL OR jsonb_typeof(points) = 'array'),
    CONSTRAINT recording_summary_warnings_array CHECK (warnings IS NULL OR jsonb_typeof(warnings) = 'array')
);

CREATE INDEX recording_summary_recording_idx ON recording_summary (recording_id, requested_at DESC);
-- felvételenként egyszerre legfeljebb egy készülő összefoglaló (dupla kattintás ellen)
CREATE UNIQUE INDEX recording_summary_one_processing_idx ON recording_summary (recording_id) WHERE status = 'PROCESSING';
