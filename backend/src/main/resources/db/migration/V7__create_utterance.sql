CREATE TABLE utterance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recording_id BIGINT not null REFERENCES recording (id) ON DELETE CASCADE,
    turn_id integer not null,
    speaker varchar(12) not null,
    similarity real,
    start_ms integer not null,
    end_ms integer not null,
    text text not null,
    asr_confidence real,

    -- Az allitas.forras (felvetel_id, turn_id) párral hivatkozik ide
    CONSTRAINT unique_recording_turn UNIQUE (recording_id, turn_id),
    CONSTRAINT speaker_values CHECK (speaker IN ('DOCTOR', 'PATIENT', 'OTHER')),
    CONSTRAINT turn_id_non_negative CHECK (turn_id >= 0),
    CONSTRAINT time_range CHECK (start_ms >= 0 AND end_ms >= start_ms),
    CONSTRAINT similarity_range CHECK (similarity BETWEEN -1 AND 1),
    CONSTRAINT asr_confidence_range CHECK (asr_confidence BETWEEN 0 AND 1)
);
