CREATE TABLE statement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    type varchar(24) not null,
    text text not null,
    label varchar(128),
    severity varchar(8) not null,
    uncertainty varchar(8),
    source jsonb not null,
    producer jsonb not null,
    clinical_time timestamptz not null,
    created_at timestamptz not null default now(),

    CONSTRAINT type_values CHECK (type IN ('DETERMINISTIC_RULE', 'RETRIEVED_FACT', 'MODEL_INFERENCE')),
    CONSTRAINT severity_values CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT uncertainty_values CHECK (uncertainty IN ('LOW', 'MEDIUM', 'HIGH')),

    -- Egy LLM-kimenet séma szinten se tűnhessen szabály-alapúnak (schema-decisions.md)
    CONSTRAINT rule_has_no_uncertainty CHECK (type <> 'DETERMINISTIC_RULE' OR uncertainty IS NULL),
    CONSTRAINT model_needs_uncertainty CHECK (type <> 'MODEL_INFERENCE' OR uncertainty IS NOT NULL),

    -- MERRE: a forrás típusa ismert
    CONSTRAINT source_type_values CHECK (source ->> 'type' IN ('AUDIO', 'DOCUMENT', 'IMAGE')),

    -- HOGY: az előállító fajtája a típushoz illik; modellnél név + seed + hash kötelező
    CONSTRAINT producer_matches_type CHECK (
        (type = 'DETERMINISTIC_RULE' AND producer ->> 'type' = 'RULE')
        OR (type = 'MODEL_INFERENCE' AND producer ->> 'type' = 'MODEL')
        OR (type = 'RETRIEVED_FACT' AND producer ->> 'type' = 'EXTRACTOR')
    ),
    CONSTRAINT model_producer_complete CHECK (
        producer ->> 'type' <> 'MODEL'
        OR (producer ->> 'modelName' IS NOT NULL
            AND producer ->> 'seed' IS NOT NULL
            AND producer ->> 'promptHash' IS NOT NULL)
    )
);

CREATE INDEX statement_patient_idx ON statement (patient_id);
