-- 1:N a statement-re: a jóváhagyási előzmény megmarad, ha az orvos meggondolja
-- magát. Érvényes állapot = a legfrissebb sor (decided_at DESC, id DESC).
CREATE TABLE statement_approval (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id BIGINT not null REFERENCES statement (id) ON DELETE CASCADE,
    user_id BIGINT not null REFERENCES app_user (id) ON DELETE RESTRICT,
    status varchar(16) not null,
    modified_text text,
    decided_at timestamptz not null default now(),

    CONSTRAINT status_values CHECK (status IN ('ACCEPTED', 'REJECTED', 'MODIFIED')),
    -- A módosított szöveg akkor és csak akkor van, ha a státusz MODIFIED
    CONSTRAINT modified_text_iff_modified CHECK ((status = 'MODIFIED') = (modified_text IS NOT NULL)),
    CONSTRAINT modified_text_not_blank CHECK (modified_text IS NULL OR btrim(modified_text) <> '')
);

-- A "legfrissebb sor" lekérdezést szolgálja ki
CREATE INDEX statement_approval_latest_idx
    ON statement_approval (statement_id, decided_at DESC, id DESC);
