CREATE TABLE allergy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    substance varchar(255) not null,
    -- Melyik (jóváhagyott) állításból származik; kézi rögzítésnél NULL
    source_statement_id BIGINT,

    CONSTRAINT substance_not_blank CHECK (btrim(substance) <> ''),
    -- Identitás-kapu: a forrás-állítás csak ugyanannak a betegnek az állítása lehet.
    -- NO ACTION: a beteg törlésekor (CASCADE mindkét táblára) nem akad el
    CONSTRAINT allergy_source_statement_fk
        FOREIGN KEY (source_statement_id, patient_id) REFERENCES statement (id, patient_id)
        ON DELETE NO ACTION
);

-- Egy betegnél egy anyag egyszer (kis-/nagybetű és szélső szóközök nélkül)
CREATE UNIQUE INDEX allergy_patient_substance_idx ON allergy (patient_id, lower(btrim(substance)));
