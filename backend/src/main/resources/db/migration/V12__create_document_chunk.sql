-- RAG-darabok a dokumentum kinyert szövegéből (diagram: doc_chunk).
-- Egyben, egyszer töltődnek fel; a text a Spring által a kinyert szövegből
-- kivágott [char_start, char_end) rész (code pointban), nem a klienstől jön.
CREATE TABLE document_chunk (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT not null REFERENCES document (id) ON DELETE CASCADE,
    text text not null,
    char_start integer not null,
    char_end integer not null,
    -- BGE-M3 dense: 1024 dimenzió
    embedding vector(1024) not null,
    -- Melyik modell számolta: különböző modellek vektorai nem összehasonlíthatók
    embedding_model varchar(128) not null,

    CONSTRAINT char_range CHECK (char_start >= 0 AND char_end > char_start),
    CONSTRAINT unique_document_range UNIQUE (document_id, char_start, char_end)
);

-- Közelítő legközelebbi-szomszéd keresés koszinusz-távolsággal
CREATE INDEX document_chunk_embedding_idx
    ON document_chunk USING hnsw (embedding vector_cosine_ops);
