-- Epikrízis: egy ellátás (medical_care) leleteiből, hangfelvétel-átiratából és a beteg aktuális
-- gyógyszereiből — docs/epicrisis.md. Sablon: fejléc (Beteg, TAJ, Dátum — a Spring tölti a DB-ből, nem a
-- modell), DIAGNÓZISOK, KRITIKUS MEGÁLLAPÍTÁSOK, JAVASLATOK.
-- TUDATOS DÖNTÉS: külön tábla, NEM statement — ugyanaz a kivétel, mint a medical_history-nél.
-- A leletek nincsenek tartósan az ellátáshoz kötve: generáláskor az orvos választja ki őket (alapból az
-- ellátás időszakába esők), a kiválasztás az input-ban rögzül.

CREATE TABLE epicrisis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    medical_care_id BIGINT not null,
    requested_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    requested_at timestamptz not null default now(),
    status varchar(16) not null,
    completed_at timestamptz,
    error text,
    -- [{name, bnoCode, documentId, recordingId, turnIds}] — a BNO-kód csak a leletből (szó szerint)
    diagnoses jsonb,
    -- [{text, documentId, recordingId, turnIds, quote, flag}] — minden pont a forrására mutat; flag: ellenőrizendő
    findings jsonb,
    recommendations jsonb,
    warnings jsonb,
    -- a kéréskor aktív gyógyszerek pillanatképe (determinisztikus): [{id, name, dose, route, verified}]
    medications jsonb not null,
    -- a modellnek átadott adatok: {documentIds, labResultIds, recordingIds, medicationIds, allergyIds}
    input jsonb not null,
    model_name varchar(128),
    seed bigint,
    prompt_hash varchar(64),
    extractor_version varchar(64),
    -- az orvos szerkesztése (a három szakasz, a Spring által szűrt HTML); az AI eredetije nem változik
    edited_html text,
    edited_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    edited_at timestamptz,

    -- identitás-kapu: az epikrízis betege csak az ellátás betege lehet
    CONSTRAINT epicrisis_medical_care_fk FOREIGN KEY (medical_care_id, patient_id)
        REFERENCES medical_care (id, patient_id) ON DELETE CASCADE,
    CONSTRAINT epicrisis_status_values CHECK (status IN ('PROCESSING', 'DONE', 'FAILED')),
    CONSTRAINT epicrisis_done_has_content CHECK (status <> 'DONE'
        OR (diagnoses IS NOT NULL AND findings IS NOT NULL AND recommendations IS NOT NULL)),
    CONSTRAINT epicrisis_failed_has_error CHECK (status <> 'FAILED' OR error IS NOT NULL),
    CONSTRAINT epicrisis_diagnoses_array CHECK (diagnoses IS NULL OR jsonb_typeof(diagnoses) = 'array'),
    CONSTRAINT epicrisis_findings_array CHECK (findings IS NULL OR jsonb_typeof(findings) = 'array'),
    CONSTRAINT epicrisis_recommendations_array CHECK (recommendations IS NULL OR jsonb_typeof(recommendations) = 'array'),
    CONSTRAINT epicrisis_warnings_array CHECK (warnings IS NULL OR jsonb_typeof(warnings) = 'array'),
    CONSTRAINT epicrisis_medications_array CHECK (jsonb_typeof(medications) = 'array'),
    CONSTRAINT epicrisis_edit_complete CHECK (
        (edited_html IS NULL AND edited_by IS NULL AND edited_at IS NULL)
        OR (edited_html IS NOT NULL AND btrim(edited_html) <> '' AND edited_by IS NOT NULL AND edited_at IS NOT NULL)
    ),
    CONSTRAINT epicrisis_edit_only_done CHECK (edited_html IS NULL OR status = 'DONE')
);

CREATE INDEX epicrisis_patient_idx ON epicrisis (patient_id, requested_at DESC);
CREATE INDEX epicrisis_medical_care_idx ON epicrisis (medical_care_id, requested_at DESC);
-- ellátásonként egyszerre legfeljebb egy készülő epikrízis (dupla kattintás ellen)
CREATE UNIQUE INDEX epicrisis_one_processing_idx ON epicrisis (medical_care_id) WHERE status = 'PROCESSING';
