-- Klinikai státusz: AI-összefoglaló + proaktív javaslatok a beteg elmúlt 6 hónapjáról.
-- TUDATOS DÖNTÉS (a felhasználóé): külön tábla, NEM statement — így nincs mondatonkénti
-- forrás-visszakeresés és jóváhagyás. Amit megőrzünk: melyik adatokból (input), melyik
-- modellel, seeddel, prompttal készült (HOGY), és mikor (MIKOR). A "Fő eltérések" NEM innen
-- jön, hanem a determinisztikus szabálymotorból (statement, lab-reference-range).
CREATE TABLE clinical_summary (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    -- ki kérte (nullázható: bejelentkezés nélkül nem bizonyító erejű); a fiók nem törölhető, amíg van
    requested_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    requested_at timestamptz not null default now(),
    status varchar(16) not null,
    completed_at timestamptz,
    error text,
    -- a vizsgált időszak (a kéréskor: az elmúlt 6 hónap)
    period_start date not null,
    period_end date not null,
    summary text,
    -- JSON szövegtömb
    recommendations jsonb,
    -- a modellnek átadott adatok azonosítói: {labResultIds, statementIds, documentIds, medicationIds, allergyIds}
    input jsonb not null,
    -- a szövegben olyan szám, ami a bemenetben nem szerepel (pl. kitalált laborérték) — kiírjuk, nem csendes
    warnings jsonb,
    model_name varchar(128),
    seed bigint,
    prompt_hash varchar(64),
    extractor_version varchar(64),

    CONSTRAINT summary_status_values CHECK (status IN ('PROCESSING', 'DONE', 'FAILED')),
    CONSTRAINT summary_done_has_text CHECK (status <> 'DONE' OR (summary IS NOT NULL AND btrim(summary) <> '')),
    CONSTRAINT summary_failed_has_error CHECK (status <> 'FAILED' OR error IS NOT NULL),
    CONSTRAINT summary_period_order CHECK (period_start <= period_end),
    CONSTRAINT summary_recommendations_array CHECK (recommendations IS NULL OR jsonb_typeof(recommendations) = 'array'),
    CONSTRAINT summary_warnings_array CHECK (warnings IS NULL OR jsonb_typeof(warnings) = 'array')
);

CREATE INDEX clinical_summary_patient_idx ON clinical_summary (patient_id, requested_at DESC);
-- betegenként egyszerre legfeljebb egy készülő összefoglaló (dupla kattintás ellen)
CREATE UNIQUE INDEX clinical_summary_one_processing_idx ON clinical_summary (patient_id) WHERE status = 'PROCESSING';
