CREATE TABLE recording (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    user_id BIGINT not null REFERENCES app_user (id) ON DELETE RESTRICT,
    -- FK majd az encounter (ellatas) táblával együtt, külön migrációban
    encounter_id BIGINT,
    voice_profile_id BIGINT REFERENCES voice_profile (id) ON DELETE SET NULL,
    mode varchar(8) not null,
    status varchar(16) not null default 'RECORDING',
    audio_path text not null,
    duration_sec integer,
    asr_model varchar(128) not null,
    recorded_at timestamptz,

    CONSTRAINT mode_values CHECK (mode IN ('SBO', 'ECHO')),
    CONSTRAINT status_values CHECK (status IN ('RECORDING', 'PROCESSING', 'DONE', 'FAILED')),
    CONSTRAINT duration_non_negative CHECK (duration_sec >= 0)
);

CREATE INDEX recording_patient_idx ON recording (patient_id);
CREATE INDEX recording_user_idx ON recording (user_id);
