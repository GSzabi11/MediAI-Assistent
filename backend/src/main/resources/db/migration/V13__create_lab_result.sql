-- Az összetett FK célja (identitás-kapu): a laborsor dokumentuma csak a laborsor
-- betegének dokumentuma lehet
ALTER TABLE document ADD CONSTRAINT unique_document_patient UNIQUE (id, patient_id);

CREATE TABLE lab_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    document_id BIGINT,
    group_name varchar(128),
    name varchar(255) not null,
    -- CLAUDE.md: numerikus érték a motoroknak; cenzorált/kvalitatív eredmény
    -- (<0,5, negatív) nem kerülhet be, és nem kerekítünk csendben
    value_num numeric(12,4) not null,
    unit varchar(32),
    ref_low numeric(12,4),
    ref_high numeric(12,4),
    measured_at timestamptz not null,
    code varchar(64),

    CONSTRAINT ref_range_order CHECK (ref_low IS NULL OR ref_high IS NULL OR ref_low <= ref_high),
    -- NO ACTION: a dokumentum nem törölhető, amíg laborsor hivatkozik rá, de a beteg
    -- törlésekor (CASCADE mindkét táblára) nem akad el
    CONSTRAINT lab_result_document_fk
        FOREIGN KEY (document_id, patient_id) REFERENCES document (id, patient_id)
        ON DELETE NO ACTION
);

-- Trend-lekérdezésekhez: egy beteg egy vizsgálata időrendben
CREATE INDEX lab_result_patient_name_time_idx ON lab_result (patient_id, name, measured_at);
CREATE INDEX lab_result_document_idx ON lab_result (document_id);
