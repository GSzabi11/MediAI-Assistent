CREATE TABLE document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    -- A tárolási mappához relatív út; maga a fájl nincs az adatbázisban
    storage_path text not null,
    type varchar(32) not null,
    mime_type varchar(128) not null,
    size_bytes bigint not null,
    sha256 varchar(64) not null,
    -- Egyszer állítható be (NULL → szöveg), utána nem változik: a statement.source
    -- karakterpozícióval hivatkozik rá
    extracted_text text,
    clinical_date date,
    uploaded_at timestamptz not null default now(),

    CONSTRAINT type_values CHECK (type IN ('LAB', 'AMBULANCE', 'IMAGING')),
    CONSTRAINT size_positive CHECK (size_bytes > 0),
    CONSTRAINT sha256_format CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT extracted_text_not_blank CHECK (extracted_text IS NULL OR btrim(extracted_text) <> ''),
    -- Ugyanaz a lelet kétszer ne kerüljön be ugyanahhoz a beteghez
    CONSTRAINT unique_patient_sha256 UNIQUE (patient_id, sha256)
);
