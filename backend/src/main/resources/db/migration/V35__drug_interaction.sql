-- Gyógyszer-interakció (docs/drug-interaction.md): determinisztikus szabály, nem LLM.
-- Referenciaadat helyi táblákban, havi frissítéssel — futás közben semmi nem megy ki a hálózatra:
--   PUPHA (NEAK Publikus Gyógyszertörzs): magyar készítménynév → ATC-kód
--   DDInter 2.0 (CC BY-NC-SA 4.0): hatóanyag-párok interakciója, súlyossággal
--   ATC → DDInter-hatóanyag: az ATC angol nevéből, ill. az RxNorm ATC-leképezéséből (frissítéskor, csak
--   az ATC-kód megy ki), ill. kézi szinonimából
-- A referenciatáblák beteghez nem kötődnek; a frissítés egy tranzakcióban cseréli a tartalmukat.

-- Egy sikeres betöltés (forrásonként): melyik fájlból, mikor — az állítás szövege erre hivatkozik
CREATE TABLE drug_reference_import (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source varchar(16) not null,
    version_label varchar(128) not null,
    sha256 varchar(64),
    row_count integer not null,
    imported_at timestamptz not null default now(),
    note text,
    CONSTRAINT drug_reference_import_source_values CHECK (source IN ('PUPHA', 'DDINTER', 'ATC_MAP'))
);

-- PUPHA GYOGYSZ tábla: egy sor = egy kiszerelés (TTT-kód). A márkanév-kulcs (brand_key) a név első,
-- számot még nem tartalmazó szavai, ékezet nélkül, nagybetűvel ("MAREVAN 3 MG TABLETTA" → "MAREVAN").
CREATE TABLE pupha_product (
    id BIGINT PRIMARY KEY,
    name varchar(512) not null,
    brand varchar(255),
    brand_key varchar(255) not null,
    atc_code varchar(16),
    ingredient_hu varchar(512),
    registration_no varchar(64),
    packaging varchar(512),
    on_market boolean not null
);
CREATE INDEX pupha_product_brand_key_idx ON pupha_product (brand_key);
CREATE INDEX pupha_product_atc_idx ON pupha_product (atc_code);

-- PUPHA ATCKONYV: ATC-kód magyar és angol névvel
CREATE TABLE atc_code (
    code varchar(16) PRIMARY KEY,
    name_hu varchar(512),
    name_en varchar(512),
    -- ékezet, szóköz és írásjel nélkül, kisbetűvel (DrugNames.key) — a beírt hatóanyagnév ehhez illeszkedik
    name_key varchar(512),
    name_en_key varchar(512),
    -- az angol név minden része DDInter-hatóanyagra képeződött-e (FULL), csak egy része (PARTIAL,
    -- pl. "perindopril and diuretics"), vagy egyik sem (NONE: nincs interakciós adat)
    mapping varchar(8) not null default 'NONE',
    CONSTRAINT atc_code_mapping_values CHECK (mapping IN ('FULL', 'PARTIAL', 'NONE'))
);
CREATE INDEX atc_code_name_key_idx ON atc_code (name_key);
CREATE INDEX atc_code_name_en_key_idx ON atc_code (name_en_key);

CREATE TABLE ddi_drug (
    id integer PRIMARY KEY,
    name varchar(255) not null,
    name_key varchar(255) not null
);
CREATE INDEX ddi_drug_name_key_idx ON ddi_drug (name_key);

-- Egy pár egyszer: drug_a < drug_b. level: a DDInter súlyossága
CREATE TABLE ddi_interaction (
    drug_a integer not null REFERENCES ddi_drug (id) ON DELETE CASCADE,
    drug_b integer not null REFERENCES ddi_drug (id) ON DELETE CASCADE,
    level varchar(16) not null,
    PRIMARY KEY (drug_a, drug_b),
    CONSTRAINT ddi_interaction_ordered CHECK (drug_a < drug_b),
    CONSTRAINT ddi_interaction_level_values CHECK (level IN ('Major', 'Moderate', 'Minor', 'Unknown'))
);
CREATE INDEX ddi_interaction_b_idx ON ddi_interaction (drug_b);

-- ATC-kód → DDInter-hatóanyag (kombinációnál több sor). origin: honnan jött a leképezés
CREATE TABLE atc_ddi_drug (
    atc_code varchar(16) not null,
    ddi_drug_id integer not null REFERENCES ddi_drug (id) ON DELETE CASCADE,
    origin varchar(16) not null,
    PRIMARY KEY (atc_code, ddi_drug_id),
    CONSTRAINT atc_ddi_drug_origin_values CHECK (origin IN ('ATC_NAME', 'RXNORM', 'ALIAS'))
);

-- Interakció-állítás forrása: a beteg két (vagy több) gyógyszere. Csak szabály-állításé lehet,
-- mint a LAB — egy LLM-kimenet ne hivatkozhasson úgy, mintha a szabálymotor számolta volna.
ALTER TABLE statement DROP CONSTRAINT source_type_values;
ALTER TABLE statement
    ADD CONSTRAINT source_type_values CHECK (source ->> 'type' IN ('AUDIO', 'DOCUMENT', 'IMAGE', 'LAB', 'MEDICATION')),
    ADD CONSTRAINT medication_source_only_for_rules CHECK (source ->> 'type' <> 'MEDICATION' OR type = 'DETERMINISTIC_RULE');

-- Egy gyógyszer-párról egy szabály legfeljebb egy állítást ad (a medicationIds rendezve tárolódik)
CREATE UNIQUE INDEX statement_rule_medication_idx
    ON statement ((producer ->> 'ruleId'), (source -> 'medicationIds'))
    WHERE source ->> 'type' = 'MEDICATION';
