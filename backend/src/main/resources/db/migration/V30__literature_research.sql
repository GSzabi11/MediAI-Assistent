-- Szakirodalmi kutatás (docs/literature-research.md). Ugyanaz a kivétel, mint a clinical_summary-nél:
-- a modell kimenete (betegállapot-összefoglaló, cikk-összefoglaló, relevancia) külön táblákban él,
-- NEM statement — ezek nem a betegről szóló, jóváhagyandó állítások, hanem keresési segédanyag.
-- Amit megőrzünk: melyik modellel, seeddel, prompttal (HOGY), mikor (MIKOR), és hogy az orvos mit írt át.

-- 1) A beteg állapotának összefoglalója a kutatáshoz: az AI javasolja (+ angol keresőkifejezés), az orvos
--    átírhatja. Az AI eredeti szövege megmarad (mint a recording_summary V29 szerkesztésénél).
CREATE TABLE research_context (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    requested_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    requested_at timestamptz not null default now(),
    status varchar(16) not null,
    completed_at timestamptz,
    error text,
    summary text,
    -- angol PubMed-keresőkifejezés javaslat (csak orvosi fogalmak — ez megy ki a hálózatra)
    query text,
    -- a modellnek átadott adatok azonosítói (mint a clinical_summary.input)
    input jsonb not null,
    warnings jsonb,
    model_name varchar(128),
    seed bigint,
    prompt_hash varchar(64),
    extractor_version varchar(64),
    edited_text text,
    edited_query text,
    edited_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    edited_at timestamptz,

    CONSTRAINT research_context_status_values CHECK (status IN ('PROCESSING', 'DONE', 'FAILED')),
    CONSTRAINT research_context_done_has_text CHECK (status <> 'DONE'
        OR (summary IS NOT NULL AND btrim(summary) <> '' AND query IS NOT NULL AND btrim(query) <> '')),
    CONSTRAINT research_context_failed_has_error CHECK (status <> 'FAILED' OR error IS NOT NULL),
    CONSTRAINT research_context_warnings_array CHECK (warnings IS NULL OR jsonb_typeof(warnings) = 'array'),
    CONSTRAINT research_context_edit_complete CHECK (
        (edited_text IS NULL AND edited_query IS NULL AND edited_by IS NULL AND edited_at IS NULL)
        OR (edited_text IS NOT NULL AND btrim(edited_text) <> '' AND edited_query IS NOT NULL
            AND btrim(edited_query) <> '' AND edited_by IS NOT NULL AND edited_at IS NOT NULL)
    ),
    CONSTRAINT research_context_edit_only_done CHECK (edited_text IS NULL OR status = 'DONE')
);

CREATE INDEX research_context_patient_idx ON research_context (patient_id, requested_at DESC);
CREATE UNIQUE INDEX research_context_one_processing_idx ON research_context (patient_id) WHERE status = 'PROCESSING';

-- 2) Egy keresés. A kontextus szövege, a kiegészítő kérés és a keresőkifejezés PILLANATKÉP: a későbbi
--    szerkesztés nem írja át, mire futott a keresés és mihez mérte a modell a relevanciát.
CREATE TABLE research (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    -- a kontextus törölhető lenne a kutatás nélkül is; a pillanatkép miatt nincs rá szükség
    context_id BIGINT REFERENCES research_context (id) ON DELETE SET NULL,
    requested_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    created_at timestamptz not null default now(),
    status varchar(16) not null,
    -- keresés közbeni állapotüzenet (a Python küldi: "PubMed: 1240 találat, absztraktok letöltése…")
    progress text,
    completed_at timestamptz,
    error text,
    context_text text not null,
    extra_prompt text,
    query text not null,
    -- JSON szövegtömb: PUBMED, COCHRANE
    sources jsonb not null,
    max_results int not null,
    -- a forrásoknál talált összes (nem csak a letöltött) találat
    total_found int,

    CONSTRAINT research_status_values CHECK (status IN ('SEARCHING', 'DONE', 'FAILED')),
    CONSTRAINT research_failed_has_error CHECK (status <> 'FAILED' OR error IS NOT NULL),
    CONSTRAINT research_context_not_blank CHECK (btrim(context_text) <> ''),
    CONSTRAINT research_query_not_blank CHECK (btrim(query) <> ''),
    CONSTRAINT research_sources_array CHECK (jsonb_typeof(sources) = 'array' AND jsonb_array_length(sources) > 0),
    CONSTRAINT research_max_results_range CHECK (max_results BETWEEN 1 AND 200)
);

CREATE INDEX research_patient_idx ON research (patient_id, created_at DESC);

-- 3) A talált cikkek. A bibliográfiai adat a forrásból jön (szó szerint), az összefoglaló és a
--    relevancia a modelltől (MODEL_INFERENCE jellegű: szint + indoklás, a modell adataival).
CREATE TABLE research_article (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    research_id BIGINT not null REFERENCES research (id) ON DELETE CASCADE,
    -- sorrend a találati listában (1-től); a Cochrane-áttekintések elöl
    rank int not null,
    pmid varchar(16) not null,
    doi varchar(255),
    title text not null,
    -- JSON szövegtömb ("Vezetéknév K")
    authors jsonb not null,
    journal text,
    pub_year int,
    abstract text,
    -- JSON szövegtömb: melyik forrás találta (PUBMED, COCHRANE)
    sources jsonb not null,
    publication_types jsonb,
    -- OpenAlex cited_by_count; NULL = nem ismert (nem 0)
    citation_count int,
    eval_status varchar(16) not null default 'NONE',
    summary text,
    relevance varchar(8),
    relevance_reason text,
    eval_error text,
    -- determinisztikus ellenőrzés: pl. az összefoglalóban az absztraktban nem szereplő szám
    eval_warnings jsonb,
    eval_model varchar(128),
    eval_seed bigint,
    eval_prompt_hash varchar(64),
    evaluated_at timestamptz,
    -- az orvos döntései: kivétel a találatok közül / könyvjelző (visszanézhető kutatási eredmény)
    excluded boolean not null default false,
    bookmarked boolean not null default false,

    CONSTRAINT research_article_unique_pmid UNIQUE (research_id, pmid),
    CONSTRAINT research_article_unique_rank UNIQUE (research_id, rank),
    CONSTRAINT research_article_pmid_digits CHECK (pmid ~ '^[0-9]{1,16}$'),
    CONSTRAINT research_article_authors_array CHECK (jsonb_typeof(authors) = 'array'),
    CONSTRAINT research_article_sources_array CHECK (jsonb_typeof(sources) = 'array'),
    CONSTRAINT research_article_citations_nonneg CHECK (citation_count IS NULL OR citation_count >= 0),
    CONSTRAINT research_article_eval_status_values CHECK (eval_status IN ('NONE', 'PENDING', 'DONE', 'FAILED')),
    CONSTRAINT research_article_relevance_values CHECK (relevance IS NULL OR relevance IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT research_article_done_complete CHECK (eval_status <> 'DONE'
        OR (summary IS NOT NULL AND relevance IS NOT NULL AND relevance_reason IS NOT NULL
            AND eval_model IS NOT NULL AND eval_seed IS NOT NULL AND eval_prompt_hash IS NOT NULL)),
    CONSTRAINT research_article_failed_has_error CHECK (eval_status <> 'FAILED' OR eval_error IS NOT NULL)
);

CREATE INDEX research_article_bookmarked_idx ON research_article (research_id) WHERE bookmarked;
