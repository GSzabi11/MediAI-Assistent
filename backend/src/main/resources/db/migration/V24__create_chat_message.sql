-- Klinikai asszisztens (chat): egy orvosi kérdés és az AI-válasz a beteg adataiból (RAG).
-- TUDATOS DÖNTÉS (a felhasználóé): külön tábla, NEM statement — a válasz pontjai nem
-- jóváhagyható állítások. Amit megőrzünk, hogy utólag igazolható legyen, mit mondott a modell:
--   MIBŐL: context (a modellnek átadott, hivatkozható tények) + retrieved (a kérdéshez
--          visszakeresett dokumentum-darabok) — a válasz forrásai csak ezek közül valók lehetnek;
--   HOGY:  model_name, seed, prompt_hash, extractor_version, embedding_model;
--   MIKOR: requested_at, completed_at.
CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    -- ki kérdezett (nullázható: bejelentkezés nélkül nem bizonyító erejű); a fiók nem törölhető, amíg van
    requested_by BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    requested_at timestamptz not null default now(),
    status varchar(16) not null,
    completed_at timestamptz,
    error text,
    question text not null,
    -- a modellnek előzményként átadott korábbi kérdés-válaszok (chat_message id-k, legfeljebb 3).
    -- Nincs FK (jsonb): a hivatkozott sorok ugyanannak a betegnek a sorai, a beteggel együtt törlődnek.
    history jsonb not null default '[]',
    -- [{kind, id, label, source}] — a hivatkozható strukturált tények (labor, állítás, gyógyszer, allergia)
    context jsonb not null,
    -- [{kind, id, label, source}] — a kérdés alapján visszakeresett dokumentum-darabok (document_chunk)
    retrieved jsonb,
    -- [{text, list, heading, sources: [{type, ...}]}] — a válasz pontjai a hivatkozott forrásokkal
    answer jsonb,
    -- forrás-lefedettségből számolva (determinisztikus, nem a modell önértékelése)
    uncertainty varchar(8),
    warnings jsonb,
    model_name varchar(128),
    seed bigint,
    prompt_hash varchar(64),
    extractor_version varchar(64),
    embedding_model varchar(128),

    CONSTRAINT chat_status_values CHECK (status IN ('PROCESSING', 'DONE', 'FAILED')),
    CONSTRAINT chat_question_not_blank CHECK (btrim(question) <> '' AND char_length(question) <= 2000),
    CONSTRAINT chat_done_complete CHECK (status <> 'DONE' OR (answer IS NOT NULL AND uncertainty IS NOT NULL
                                                               AND model_name IS NOT NULL)),
    CONSTRAINT chat_failed_has_error CHECK (status <> 'FAILED' OR error IS NOT NULL),
    CONSTRAINT chat_uncertainty_values CHECK (uncertainty IS NULL OR uncertainty IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT chat_history_array CHECK (jsonb_typeof(history) = 'array'),
    CONSTRAINT chat_context_array CHECK (jsonb_typeof(context) = 'array'),
    CONSTRAINT chat_retrieved_array CHECK (retrieved IS NULL OR jsonb_typeof(retrieved) = 'array'),
    CONSTRAINT chat_answer_array CHECK (answer IS NULL OR jsonb_typeof(answer) = 'array'),
    CONSTRAINT chat_warnings_array CHECK (warnings IS NULL OR jsonb_typeof(warnings) = 'array')
);

CREATE INDEX chat_message_patient_idx ON chat_message (patient_id, requested_at DESC);
-- betegenként egyszerre legfeljebb egy készülő válasz (dupla küldés ellen)
CREATE UNIQUE INDEX chat_message_one_processing_idx ON chat_message (patient_id) WHERE status = 'PROCESSING';
