-- Az összetett FK célja (identitás-kapu): a gyógyszer forrás-állítása csak
-- ugyanannak a betegnek az állítása lehet
ALTER TABLE statement ADD CONSTRAINT unique_statement_patient UNIQUE (id, patient_id);

CREATE TABLE medication (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    name varchar(255) not null,
    active_ingredient varchar(255),
    dose numeric(10,3),
    dose_unit varchar(255),
    route varchar(255),
    -- Melyik (jóváhagyott) állításból származik; kézi rögzítésnél NULL
    source_statement_id BIGINT,
    -- Egyirányú: true → false (leállítás). Újrakezdés = új sor, az előzmény megmarad.
    active boolean not null default true,

    CONSTRAINT dose_positive CHECK (dose IS NULL OR dose > 0),
    CONSTRAINT dose_needs_unit CHECK (dose IS NULL OR dose_unit IS NOT NULL),
    -- NO ACTION: a beteg törlésekor (CASCADE mindkét táblára) nem akad el
    CONSTRAINT medication_source_statement_fk
        FOREIGN KEY (source_statement_id, patient_id) REFERENCES statement (id, patient_id)
        ON DELETE NO ACTION
);

CREATE INDEX medication_patient_idx ON medication (patient_id);
