CREATE TABLE medical_care (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT not null REFERENCES pacient (id) ON DELETE CASCADE,
    user_id BIGINT not null REFERENCES app_user (id) ON DELETE RESTRICT,
    type varchar(32) not null,
    started_at timestamptz not null default now(),
    ended_at timestamptz,

    CONSTRAINT type_values CHECK (type IN ('SBO', 'AMBULANCE', 'ECHO')),
    CONSTRAINT end_after_start CHECK (ended_at IS NULL OR ended_at >= started_at),
    -- Az összetett FK célja a recording-ból (lent)
    CONSTRAINT unique_medical_care_patient UNIQUE (id, patient_id)
);

CREATE INDEX medical_care_patient_idx ON medical_care (patient_id);

-- A V5-ben még encounter_id néven jött létre (akkor FK nélkül).
ALTER TABLE recording RENAME COLUMN encounter_id TO medical_care_id;

-- Identitás-kapu DB-szinten: a felvétel betege csak az ellátás betege lehet.
-- NO ACTION (nem RESTRICT): közvetlen törlésnél ugyanúgy tilt, de a beteg
-- törlésekor az ellátás és a felvétel is CASCADE-del törlődik, és a RESTRICT
-- az utasítás közepén, a még ki nem törölt felvételen elhasalna.
ALTER TABLE recording
    ADD CONSTRAINT recording_medical_care_fk
    FOREIGN KEY (medical_care_id, patient_id) REFERENCES medical_care (id, patient_id)
    ON DELETE NO ACTION;

CREATE INDEX recording_medical_care_idx ON recording (medical_care_id);
