CREATE TABLE access_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- NULL: nem azonosított hívó (hiányzó vagy ismeretlen X-User-Id)
    user_id BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    -- SZÁNDÉKOSAN nincs FK: a beteg törlése után is meg kell maradnia a nyomnak,
    -- hogy ki nézte meg korábban (schema-decisions.md). NULL: nem beteghez kötött hívás.
    patient_id BIGINT,
    action varchar(16) not null,
    -- HTTP metódus + út, query string NÉLKÜL (az naplókban leülepedne)
    resource varchar(255) not null,
    http_status integer not null,
    accessed_at timestamptz not null default now(),
    ip inet,

    CONSTRAINT action_values CHECK (action IN ('READ', 'WRITE', 'EXPORT'))
);

CREATE INDEX access_log_patient_idx ON access_log (patient_id, accessed_at);
CREATE INDEX access_log_user_idx ON access_log (user_id, accessed_at);

-- Csak hozzáfűzés: egy utólag átírható audit-napló nem bizonyíték.
CREATE FUNCTION access_log_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'access_log is append-only (% not allowed)', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER access_log_no_update_delete
    BEFORE UPDATE OR DELETE ON access_log
    FOR EACH ROW EXECUTE FUNCTION access_log_append_only();

CREATE TRIGGER access_log_no_truncate
    BEFORE TRUNCATE ON access_log
    FOR EACH STATEMENT EXECUTE FUNCTION access_log_append_only();
